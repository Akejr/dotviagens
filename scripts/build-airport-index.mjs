// Run after replacing public/airports.json (OurAirports snapshot): node scripts/build-airport-index.mjs
// 1. Keeps only airports with scheduled passenger flights: rank 0 in airports.json (OurAirports
//    scheduled_service = yes), plus KEEP (Angolan domestic airports with flights that the snapshot
//    marks without them). Military bases, airfields and closed airports leave the search.
// 2. Writes server/airport-codes.mjs: the airport codes the server accepts and, for searches to
//    every airport of a country ("Brasil (todos os aeroportos)"), the countries with 2 or more
//    airports and their Google location id (kgmid = Freebase ID, read from Wikidata, CC0).
// 3. Writes public/airport-countries.js: the same country codes, for the search box.
// Then run node scripts/build-airports-popular.mjs (the popular list is read from airports.json).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const KEEP = new Set(['VHC', 'LUO', 'SVP', 'UGO']);
const file = join(ROOT, 'public', 'airports.json');
const rows = JSON.parse(readFileSync(file, 'utf8'));
const kept = rows.filter(a => a.rank === 0 || KEEP.has(a.code)).map(a => (KEEP.has(a.code) ? { ...a, rank: 0 } : a));
writeFileSync(file, JSON.stringify(kept));
console.log(`airports.json: ${rows.length} -> ${kept.length} aeroportos (sem voos regulares removidos: ${rows.length - kept.length})`);

// ISO 3166-1 alpha-2 -> Freebase ID. A code with two ids keeps the shorter (the main entity).
const query = 'SELECT ?iso ?fb WHERE { ?c wdt:P297 ?iso . ?c wdt:P646 ?fb . }';
const response = await fetch(`https://query.wikidata.org/sparql?format=json&query=${encodeURIComponent(query)}`, {
  headers: { 'User-Agent': 'DOT-Viagens-build/1.0 (https://www.dotviagens.com)', Accept: 'application/sparql-results+json' },
  signal: AbortSignal.timeout(90000),
});
if (!response.ok) throw new Error(`Wikidata respondeu ${response.status}`);
const kgmid = new Map();
for (const { iso, fb } of (await response.json()).results.bindings.map(b => ({ iso: b.iso.value, fb: b.fb.value }))) {
  if (!/^[A-Z]{2}$/.test(iso) || !/^\/m\/[0-9a-z_]+$/.test(fb)) continue;
  const previous = kgmid.get(iso);
  if (!previous || fb.length < previous.length) kgmid.set(iso, fb);
}

const perCountry = new Map();
for (const a of kept) perCountry.set(a.countryCode, (perCountry.get(a.countryCode) || 0) + 1);
const countries = [...perCountry].filter(([code, count]) => count >= 2 && kgmid.has(code)).map(([code]) => code).sort();
const missing = [...perCountry].filter(([code, count]) => count >= 2 && !kgmid.has(code)).map(([code]) => code);

const codes = kept.map(a => a.code);
writeFileSync(join(ROOT, 'server', 'airport-codes.mjs'), `// Generated by scripts/build-airport-index.mjs from public/airports.json. Do not edit by hand.
// Airports with scheduled flights (the codes the server accepts).
export const airports=new Set(${JSON.stringify(codes).replace(/","/g, '", "')});
// Countries with 2 or more of those airports: ISO code -> Google location id (kgmid), for the
// searches to every airport of a country ("Brasil (todos os aeroportos)").
export const countryPlaces=new Map(${JSON.stringify(countries.map(code => [code, kgmid.get(code)]))});
`);
writeFileSync(join(ROOT, 'public', 'airport-countries.js'), `// Generated by scripts/build-airport-index.mjs. Do not edit by hand.
// Countries that can be searched as a whole ("Brasil (todos os aeroportos)"): 2 or more airports with flights.
export const ALL_AIRPORT_COUNTRIES = new Set(${JSON.stringify(countries)});
`);
console.log(`server/airport-codes.mjs: ${codes.length} aeroportos, ${countries.length} países com pesquisa por país${missing.length ? ` (sem kgmid: ${missing.join(' ')})` : ''}`);
