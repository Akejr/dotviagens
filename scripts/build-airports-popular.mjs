// Builds public/airports-popular.js: a few dozen airports taken from public/airports.json.
// The home search uses them immediately (no wait for the full catalogue of ~9 000 airports, which
// loads in the background) and shows them as suggestions when the search box is empty.
// Run after changing CODES or airports.json: node scripts/build-airports-popular.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
// Order = order of the suggestions. Angola first, then the most searched routes from Luanda.
const CODES = [
  'NBJ', 'LIS', 'OPO', 'GRU', 'GIG', 'DXB', 'JNB', 'CPT', 'WDH', 'CDG', 'IST', 'DOH', 'ADD', 'CMN', 'MAD', 'LHR', 'FRA', 'BRU', 'AMS', 'FCO',
  'FIH', 'BZV', 'LOS', 'ACC', 'MPM', 'NBO', 'TMS', 'RAI', 'PEK', 'PVG', 'CAN', 'JFK', 'MIA', 'HAV', 'FAO',
  'SDD', 'CBT', 'CAB', 'NOV', 'SZA', 'MSZ', 'VHC', 'LUO', 'SPP', 'VPE', 'DUE', 'MEG', 'SVP', 'UGO', 'SSY',
];
const rows = JSON.parse(readFileSync(join(ROOT, 'public', 'airports.json'), 'utf8'));
const byCode = new Map(rows.map(row => [row.code, row]));
const missing = CODES.filter(code => !byCode.has(code));
if (missing.length) {
  console.error(`códigos que não existem em airports.json: ${missing.join(', ')}`);
  process.exit(1);
}
const picked = CODES.map(code => byCode.get(code));
writeFileSync(join(ROOT, 'public', 'airports-popular.js'), `// Generated by scripts/build-airports-popular.mjs from airports.json. Do not edit by hand.
// Popular airports, available before the full catalogue loads (same fields as airports.json).
export const POPULAR = ${JSON.stringify(picked)};
`);
console.log(`airports-popular.js: ${picked.length} aeroportos (${Math.round(JSON.stringify(picked).length / 1024)} KB)`);
for (const a of picked) console.log(`  ${a.code} ${a.city} · ${a.country} · ${a.name} · rank ${a.rank}`);
